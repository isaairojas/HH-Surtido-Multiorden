const CASOS_ARMADO: Caso[] = PRESETS_ARMADO.map((p) =>
  p.enListado && ARMADO_EN_LISTADO[p.id]
    ? {
        id: `armado-${p.id}`,
        cambio: 'armado',
        requisito: p.requisito,
        escenario: p.escenario,
        ruta: '/surtido',
        ...ARMADO_EN_LISTADO[p.id],
      }
    : {
        id: `armado-${p.id}`,
        cambio: 'armado',
        requisito: p.requisito,
        escenario: p.escenario,
        armado: p.id,
        pasos: [p.descripcion],
        esperado: p.esperado,
      },
);

export const CASOS: Caso[] = [...CASOS_HH, ...CASOS_ARMADO];

export const casoPorId = (id: string | null) => (id ? CASOS.find((x) => x.id === id) : undefined);

/** Liga de un caso: la semilla va en la query y la pantalla en el hash; el armado es su propia página. */
export function urlCaso(x: Caso): string {
  if (x.armado) return `?caso=${x.id}#/armado/${x.armado}`;
  return `?escenario=${x.semilla}&caso=${x.id}#${x.ruta}`;
}

/** Carpeta del spec, para mostrarla junto al requisito. */
export const carpetaDe = (id: CambioId) => CAMBIOS.find((x) => x.id === id)?.carpeta ?? LISTADO;
